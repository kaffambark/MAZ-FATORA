let I18N_LANG = 'fr';

/* Remplacement des variables {nom} (toutes les occurrences) */
function i18nTr(key, vars) {
  const dict = I18N_DICT[I18N_LANG] || I18N_DICT.fr;
  let s = dict[key];
  if (s === undefined) s = I18N_DICT.fr[key];
  if (s === undefined) return key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k] === undefined || vars[k] === null ? '' : vars[k]));
    }
  }
  return s;
}

/* Remplit les éléments statiques marqués (root = document entier par défaut) */
function i18nApplyStatic(root) {
  if (typeof document === 'undefined') return;
  const scope = root || document;
  if (scope.querySelectorAll) {
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = i18nTr(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = i18nTr(el.getAttribute('data-i18n-html')); });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', i18nTr(el.getAttribute('data-i18n-ph'))); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', i18nTr(el.getAttribute('data-i18n-title'))); });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', i18nTr(el.getAttribute('data-i18n-aria'))); });
  }
  if (scope.matches && scope.matches('[data-i18n]')) scope.textContent = i18nTr(scope.getAttribute('data-i18n'));
}

/* Change la langue : <html lang dir> + libellés statiques.
   opts.rtl === false : on laisse la direction inchangée (facture bilingue, toujours LTR). */
function i18nSetLang(lang, opts) {
  I18N_LANG = (lang === 'ar') ? 'ar' : 'fr';
  if (typeof document !== 'undefined' && document.documentElement) {
    const html = document.documentElement;
    html.setAttribute('lang', I18N_LANG);
    const rtl = !opts || opts.rtl !== false;
    if (rtl) html.setAttribute('dir', I18N_LANG === 'ar' ? 'rtl' : 'ltr');
    i18nApplyStatic(document);
  }
  return I18N_LANG;
}

const I18N_API = {
  tr: i18nTr,
  setLang: i18nSetLang,
  applyStatic: i18nApplyStatic,
  getLang: () => I18N_LANG,
  DICT: I18N_DICT
};

if (typeof module === 'object' && module.exports) module.exports = I18N_API;
if (typeof window !== 'undefined') {
  window.I18N = I18N_API;
  window.tr = i18nTr;
}
